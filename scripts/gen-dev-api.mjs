// Pack pkg/dev-extension/dev-api/server.mjs into dev-api.generated.ts, so the in-cluster API is
// written as a file - with a syntax check and no escaping - and shipped as the string the
// ConfigMap needs. `node scripts/gen-dev-api.mjs`; the output is committed.
//
// The server runs from a ConfigMap as one file with no node_modules and no second file to
// import, so a `./thing.mjs` of its own is inlined here instead of being shipped beside it.
// That is what lets a piece of the server - the WebSocket framing, say - be a module `node
// --test` can get at, rather than a few hundred lines of bit-shifting with no way to test it.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const DIR = path.join(here, '..', 'pkg', 'dev-extension', 'dev-api');
const SRC = path.join(DIR, 'server.mjs');
const OUT = path.join(here, '..', 'pkg', 'dev-extension', 'dev-api.generated.ts');

/**
 * `import { a, b } from './x.mjs';` - a sibling module - or from `../x.mjs`, a plain module the
 * extension's own pages share. Its top-level names land in server.mjs's scope, and
 * tests/housekeeping.test.mjs checks that the result still parses.
 */
const LOCAL_IMPORT = /^import\s*\{[^}]*\}\s*from\s*'(\.\.?\/[\w-]+\.mjs)';$/gm;

const source = fs.readFileSync(SRC, 'utf8').replace(LOCAL_IMPORT, (line, file) => {
  const body = fs.readFileSync(path.join(DIR, file), 'utf8')
    // Only at the start of a line: `export` anywhere else is part of a string or a comment.
    .replace(/^export /gm, '')
    .trim();

  return [`// ── inlined from ${ file } ──`, body, `// ── end of ${ file } ──`].join('\n');
});

const generated = `// Generated by scripts/gen-dev-api.mjs from pkg/dev-extension/dev-api/server.mjs. Do not edit.
/* eslint-disable */
export const DEV_API_SERVER = ${ JSON.stringify(source) };
`;

// `--check` writes nothing and fails when the committed file is not what this would write.
if (process.argv.includes('--check')) {
  process.exit(fs.readFileSync(OUT, 'utf8') === generated ? 0 : 1);
}
fs.writeFileSync(OUT, generated);
console.log(`dev-api: ${ source.length } bytes (${ fs.statSync(SRC).size } on disk) -> ${ path.relative(process.cwd(), OUT) }`);
